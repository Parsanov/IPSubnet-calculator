import pytest
from subnetcalc.core import validIp4v, ipToBinarySystem, octetsToBinary



@pytest.mark.parametrize("ip, expected", [
    ("192.168.1", False),
    ("1.2.3.4.5", False),
    ("192..1.1", False),
    ("192.168.-1.1", False),
    ("256.1.1.1", False),
    ("0.0.0.0", True),
    ("255.255.255.255", True),
    ("192.168.1.1 ", False),
    ("192.168.01.1",False),
    ("", False),
    ("192.168.1.1", True),  
    ("10.0.0.1", True),     
    ("8.8.8.8", True),      
])
def test_is_valid_ip(ip, expected):
    
    assert validIp4v(ip) == expected


@pytest.mark.parametrize("octet, expected", [
    (0,   "00000000"),  # нижня межа
    (1,   "00000001"),  # перевірка, що нулі зліва дописуються до 8 цифр
    (10,  "00001010"),  # маленьке число, 8 + 2
    (127, "01111111"),  # старший біт ще 0
    (128, "10000000"),  # старший біт уже 1, сусід 127
    (168, "10101000"),  # 128 + 32 + 8
    (192, "11000000"),  # типовий октет маски
    (224, "11100000"),  # типовий октет маски
    (255, "11111111"),  # верхня межа
])
def test_octet_to_binary(octet, expected):
    assert octetsToBinary(octet) == expected

@pytest.mark.parametrize("ip, expected", [
    ("192.168.0.1",     ["11000000", "10101000", "00000000", "00000001"]),  # приватна адреса
    ("10.0.0.1",        ["00001010", "00000000", "00000000", "00000001"]),  # одноцифрові октети
    ("0.0.0.0",         ["00000000", "00000000", "00000000", "00000000"]),  # усі нулі
    ("255.255.255.255", ["11111111", "11111111", "11111111", "11111111"]),  # усі одиниці
    ("255.255.255.0",   ["11111111", "11111111", "11111111", "00000000"]),  # маска /24
])
def test_ip_to_binary(ip, expected):
    assert ipToBinarySystem(ip) == expected